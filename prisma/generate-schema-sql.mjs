/**
 * Write the Postgres DDL for the current schema into a module the app can run.
 *
 * `prisma db push` needs the Prisma CLI and a direct connection, neither of which a deployed
 * serverless function has. So the same statements the CLI would run are generated at build time
 * and shipped inside the bundle, and the app can create its own tables when the build could not.
 *
 * Always generated against the postgresql provider, whatever the checked-in schema says, so the
 * output does not change depending on where it was run.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, unlinkSync } from "node:fs";

const SCHEMA = "prisma/schema.prisma";
const TEMP = "prisma/.schema.postgres.prisma";
const OUT = "src/lib/catalog/schema-sql.ts";
const DATASOURCE_PROVIDER = /(datasource\s+db\s*\{[^}]*?provider\s*=\s*)"sqlite"/;

const schema = readFileSync(SCHEMA, "utf8");
const postgres = schema.replace(DATASOURCE_PROVIDER, '$1"postgresql"');
if (DATASOURCE_PROVIDER.test(postgres)) throw new Error("could not switch the datasource to postgresql");

writeFileSync(TEMP, postgres);
let sql;
try {
  sql = execFileSync("npx", ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", TEMP, "--script"], { encoding: "utf8" });
} finally {
  try { unlinkSync(TEMP); } catch {}
}

if (!/CREATE TABLE/i.test(sql)) throw new Error("prisma migrate diff produced no tables");

// The same for SQLite, which the desktop copies run on: an upgraded install keeps its database, so
// the columns and tables a release adds must reach it the same way. See schema-repair.ts.
const SQLITE_TEMP = "prisma/.schema.sqlite.prisma";
writeFileSync(SQLITE_TEMP, schema.replace(/(datasource\s+db\s*\{[^}]*?provider\s*=\s*)"postgresql"/, '$1"sqlite"'));
let sqlite;
try {
  sqlite = execFileSync("npx", ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", SQLITE_TEMP, "--script"], { encoding: "utf8" });
} finally {
  try { unlinkSync(SQLITE_TEMP); } catch {}
}
if (!/CREATE TABLE/i.test(sqlite)) throw new Error("prisma migrate diff produced no SQLite tables");

writeFileSync(OUT, `// Generated by prisma/generate-schema-sql.mjs — do not edit by hand.
//
// The Postgres DDL for prisma/schema.prisma, as \`prisma db push\` would apply it to an empty
// database. Shipped inside the bundle so a deployed app can create its own tables when the build
// could not reach the database directly enough to do it.
//
// Regenerate with: node prisma/generate-schema-sql.mjs

export const SCHEMA_SQL = ${JSON.stringify(sql)};

/** The same schema as SQLite DDL, for the desktop copies' own database. */
export const SCHEMA_SQL_SQLITE = ${JSON.stringify(sqlite)};

/**
 * The DDL as separate statements, in the order they must run.
 *
 * Prisma writes one statement per block, each under a \`-- CreateTable\` style comment and ending
 * with a semicolon at the end of a line, and never puts a semicolon inside a quoted literal — so
 * splitting on a line-final semicolon is safe here. The leading comments are dropped because they
 * are the only thing in a block that is not SQL to execute.
 */
export function schemaStatements(dialect: "postgres" | "sqlite" = "postgres"): string[] {
  return (dialect === "sqlite" ? SCHEMA_SQL_SQLITE : SCHEMA_SQL).split(/;\\s*$/m)
    .map((block) => block.replace(/^\\s*(--[^\\n]*\\n)+/, "").trim())
    .filter((statement) => statement.length > 0);
}
`);
console.log(`[schema-sql] wrote ${OUT} (${sql.split("\n").filter((l) => /^CREATE TABLE/i.test(l)).length} tables)`);
